<#
.SYNOPSIS
  Combine the harness levels into one AGENTS.md (PowerShell version of build-agents-md.sh).

.DESCRIPTION
  Reads <dir>/.harness/level1/AGENTS.md, .harness/division/DIVISION.md (optional),
  .harness/kit/AGENTS.md and .harness/project/AGENTS.md, and writes <dir>/AGENTS.md,
  which every agent reads (Claude Code via CLAUDE.md). The output is identical to the
  Bash version, so either can regenerate or check the file.

  With no Path: the parent folder when this script lives in .harness/, otherwise the
  current folder.

.PARAMETER Check
  Exit 1 if AGENTS.md is missing or out of date, without changing it.

.EXAMPLE
  pwsh .harness/build-agents-md.ps1
  pwsh .harness/build-agents-md.ps1 -Check
#>
param(
  [string]$Path = "",
  [switch]$Check
)
$ErrorActionPreference = "Stop"

if (-not $Path) {
  if ((Split-Path -Leaf $PSScriptRoot) -eq ".harness") { $Path = Split-Path -Parent $PSScriptRoot } else { $Path = "." }
}
$H = Join-Path $Path ".harness"
if (-not (Test-Path -LiteralPath $H -PathType Container)) { [Console]::Error.WriteLine("error: no .harness folder in $Path"); exit 2 }

$parts = @((Join-Path $H "level1/AGENTS.md"))
$division = Join-Path $H "division/DIVISION.md"
if (Test-Path -LiteralPath $division -PathType Leaf) { $parts += $division }
$parts += (Join-Path $H "kit/AGENTS.md")
$parts += (Join-Path $H "project/AGENTS.md")
foreach ($p in $parts) {
  if (-not (Test-Path -LiteralPath $p -PathType Leaf)) { [Console]::Error.WriteLine("error: missing $p"); exit 2 }
}

function Read-Normalized([string]$file) {
  # Strip carriage returns and trailing newlines so output is identical on every OS.
  return ([IO.File]::ReadAllText((Resolve-Path -LiteralPath $file).Path) -replace "`r", "").TrimEnd("`n")
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("<!-- GENERATED by build-agents-md.sh. Do not edit. -->")
$lines.Add('> This file is generated. To change project rules, edit `.harness/project/AGENTS.md`, then run `bash .harness/build-agents-md.sh` (or `pwsh .harness/build-agents-md.ps1`). Levels below add to the ones above and may only tighten them.')
foreach ($p in $parts) {
  $lines.Add("")
  $lines.Add((Read-Normalized $p))
}
$generated = ($lines -join "`n") + "`n"

$out = Join-Path $Path "AGENTS.md"
if ($Check) {
  if ((Test-Path -LiteralPath $out -PathType Leaf) -and
      (([IO.File]::ReadAllText((Resolve-Path -LiteralPath $out).Path) -replace "`r", "") -ceq $generated)) {
    Write-Output "AGENTS.md is up to date."
    exit 0
  }
  [Console]::Error.WriteLine("AGENTS.md is missing or out of date. Edit .harness/project/AGENTS.md, not AGENTS.md, then run: pwsh .harness/build-agents-md.ps1")
  exit 1
}

$full = Join-Path (Resolve-Path -LiteralPath $Path).Path "AGENTS.md"
[IO.File]::WriteAllText($full, $generated, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "Wrote $out from $($parts.Count) levels."
exit 0
