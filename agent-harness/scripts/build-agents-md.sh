#!/usr/bin/env bash
# build-agents-md.sh: combine the harness levels into one AGENTS.md.
#
# Usage: build-agents-md.sh [--check] [project-dir]
#
# Reads   <dir>/.harness/level1/AGENTS.md
#         <dir>/.harness/division/DIVISION.md   (optional)
#         <dir>/.harness/kit/AGENTS.md
#         <dir>/.harness/project/AGENTS.md
# Writes  <dir>/AGENTS.md, which every agent reads (Claude Code via CLAUDE.md).
#
# --check  exit 1 if AGENTS.md is missing or out of date, without changing it.
#          Use it in CI so hand edits to AGENTS.md are caught.
#
# With no project-dir: the parent folder when this script lives in .harness/,
# otherwise the current folder.
set -euo pipefail

CHECK=0 TARGET=""
for arg in "$@"; do
  case "$arg" in
    --check) CHECK=1 ;;
    -h|--help) sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    -*) printf 'error: unknown option: %s\n' "$arg" >&2; exit 2 ;;
    *) TARGET="$arg" ;;
  esac
done
if [ -z "$TARGET" ]; then
  SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  if [ "$(basename "$SCRIPT_DIR")" = ".harness" ]; then TARGET="$(dirname "$SCRIPT_DIR")"; else TARGET="."; fi
fi
[ -d "$TARGET/.harness" ] || { printf 'error: no .harness folder in %s\n' "$TARGET" >&2; exit 2; }

H="$TARGET/.harness"
PARTS=("$H/level1/AGENTS.md")
[ -f "$H/division/DIVISION.md" ] && PARTS+=("$H/division/DIVISION.md")
PARTS+=("$H/kit/AGENTS.md" "$H/project/AGENTS.md")
for p in "${PARTS[@]}"; do
  [ -f "$p" ] || { printf 'error: missing %s\n' "$p" >&2; exit 2; }
done

generate() {
  printf '%s\n' "<!-- GENERATED by build-agents-md.sh. Do not edit. -->"
  printf '%s\n' "> This file is generated. To change project rules, edit \`.harness/project/AGENTS.md\`, then run \`bash .harness/build-agents-md.sh\` (or \`pwsh .harness/build-agents-md.ps1\`). Levels below add to the ones above and may only tighten them."
  local p
  for p in "${PARTS[@]}"; do
    printf '\n'
    # Strip carriage returns and trailing blank lines so output is identical on every OS.
    printf '%s\n' "$(tr -d '\r' < "$p")"
  done
}

OUT="$TARGET/AGENTS.md"
if [ "$CHECK" -eq 1 ]; then
  if [ -f "$OUT" ] && diff -q <(generate) <(tr -d '\r' < "$OUT") >/dev/null; then
    echo "AGENTS.md is up to date."
    exit 0
  fi
  echo "AGENTS.md is missing or out of date. Edit .harness/project/AGENTS.md, not AGENTS.md, then run: bash .harness/build-agents-md.sh" >&2
  [ -f "$OUT" ] && diff <(generate) <(tr -d '\r' < "$OUT") | head -n 40 >&2 || true
  exit 1
fi

generate > "$OUT.tmp" && mv "$OUT.tmp" "$OUT"
echo "Wrote $OUT from ${#PARTS[@]} levels."
